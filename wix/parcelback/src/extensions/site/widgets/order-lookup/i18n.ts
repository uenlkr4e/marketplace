const MESSAGES: Record<string, Messages> = { en, de, fr, es, it, nl, pt };

export const LANGUAGES = [
  { id: 'en', name: 'English' },
  { id: 'de', name: 'Deutsch' },
  { id: 'fr', name: 'Français' },
  { id: 'es', name: 'Español' },
  { id: 'it', name: 'Italiano' },
  { id: 'nl', name: 'Nederlands' },
  { id: 'pt', name: 'Português' },
] as const;

/** Picks a supported language from a tag like "de-AT"; falls back to English. */
export function resolveLanguage(...candidates: (string | null | undefined)[]): string {
  for (const tag of candidates) {
    const code = tag?.slice(0, 2).toLowerCase();
    if (code && code in MESSAGES) return code;
  }
  return 'en';
}

export type Translate = (key: string, vars?: Record<string, string | number>) => string;

/** Returns a translator; `t.has(key)` tells whether a key exists. */
export function translator(lang: string): Translate & { has: (key: string) => boolean } {
  const messages = MESSAGES[lang] ?? en;
  const t = ((key: string, vars: Record<string, string | number> = {}) => {
    const text = (messages as Record<string, string>)[key] ?? (en as Record<string, string>)[key] ?? key;
    return text.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
  }) as Translate & { has: (key: string) => boolean };
  t.has = (key) => key in en;
  return t;
}
